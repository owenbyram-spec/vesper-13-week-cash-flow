"""
Stable alert fingerprints + sticky-dismissal rules.

Both alert streams (InsightAnomaly and WatchdogAlert) are regenerated by
recurring jobs (the analysis pipeline and the nightly watchdog loop). Without
a stable identity for "the same underlying condition", regeneration resurrects
alerts the user already dismissed/acknowledged. This module provides:

- compute_fingerprint / anomaly_fingerprint / watchdog_fingerprint:
  a deterministic hash of (stream, company, detector/type, scope-period,
  entity key). Same condition => same fingerprint across runs.
- is_materially_worse: the single definition of when a previously dismissed
  condition is allowed to re-alert.
- dismissed_anomaly_blocks / acknowledged_watchdog_blocks: the suppression
  checks the regeneration paths call before creating a row.

Tenant safety: every fingerprint embeds company_id and every suppression query
filters on company_id — fingerprints never match across tenants.
"""
import hashlib
from datetime import datetime, timedelta
from typing import Any, Dict, Optional

# How long a dismissal "sticks". A dismissed condition older than this window
# is allowed to re-alert even if unchanged — a quarter-old dismissal should not
# silence a still-true critical condition forever.
DISMISSAL_STICKY_DAYS = 90

# "Materially worse" definition (see is_materially_worse below):
# a re-alert for a previously dismissed condition is legitimate only if
#   (a) the severity escalated (info -> warning -> critical), OR
#   (b) the magnitude of the driving metric grew by >= 20% in absolute terms
#       versus the value recorded on the dismissed alert.
# 20% is intentionally simple/conservative: small drift in a z-score or dollar
# value is "the same condition persisting", not new information.
MATERIAL_WORSENING_RATIO = 1.20

_SEVERITY_RANK = {"info": 0, "warning": 1, "critical": 2}

# Which data_ref key carries the magnitude of each anomaly detector's signal,
# used for the "materially worse" comparison.
_ANOMALY_MAGNITUDE_KEYS = {
    "unusual_transaction": "z_score",
    "cogs_spike": "z_score",
    "negative_balance": "cash",
    "revenue_concentration": "concentration_pct",
    "ar_aging_90plus": "pct",
}


def compute_fingerprint(*parts: Any) -> str:
    """Deterministic fingerprint over ordered identity parts (None -> '')."""
    normalized = "|".join("" if p is None else str(p) for p in parts)
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()[:32]


# ─────────────────────────────────────────────────────────────────────────────
# InsightAnomaly (analysis pipeline stream)
# ─────────────────────────────────────────────────────────────────────────────

def _anomaly_entity_key(anomaly_type: str, data_ref: Dict[str, Any]) -> str:
    """Entity-level identity within a detector. Per-transaction detectors key
    on the transaction; monthly detectors key on the month; balance/ratio
    detectors are one-per-period (empty key — the period scopes them)."""
    if anomaly_type == "unusual_transaction":
        return f"{data_ref.get('type', '')}:{data_ref.get('id', '')}"
    if anomaly_type == "cogs_spike":
        return str(data_ref.get("month", ""))
    return ""


def anomaly_fingerprint(company_id: str, anomaly_type: str, period: Optional[str],
                        data_ref: Optional[Dict[str, Any]]) -> str:
    entity = _anomaly_entity_key(anomaly_type, data_ref or {})
    return compute_fingerprint("anomaly", company_id, anomaly_type, period, entity)


def anomaly_magnitude(anomaly_type: str, data_ref: Optional[Dict[str, Any]]) -> Optional[float]:
    key = _ANOMALY_MAGNITUDE_KEYS.get(anomaly_type)
    if not key:
        return None
    value = (data_ref or {}).get(key)
    try:
        return float(value) if value is not None else None
    except (TypeError, ValueError):
        return None


# ─────────────────────────────────────────────────────────────────────────────
# WatchdogAlert (nightly watchdog stream)
# ─────────────────────────────────────────────────────────────────────────────

def watchdog_fingerprint(company_id: str, alert_type: str, period: Optional[str] = None, *,
                         related_entity_type: Optional[str] = None,
                         related_entity_id: Optional[Any] = None,
                         context: Optional[Dict[str, Any]] = None) -> str:
    """Identity of a watchdog condition.

    - Transaction-shaped alerts (context carries vendor/date/amount) are keyed
      by the transaction identity and NOT the period: a specific payment is the
      same condition whichever monthly run re-detects it.
    - Entity-shaped alerts (covenant etc.) key on the related entity + period.
    - Vendor-shaped alerts (e.g. BUDGET_OVERRUN) key on the vendor + period.
    - Condition-shaped alerts (NEGATIVE_CASH, LOW_RUNWAY, ...) are one per
      period: dismissing May's low-runway alert does not silence June's.
    """
    ctx = context or {}
    if ctx.get("date") is not None and ctx.get("amount") is not None:
        entity = f"{ctx.get('vendor', '')}:{ctx.get('date', '')}:{ctx.get('amount', '')}"
        scope = ""  # txn identity is already time-anchored
    elif related_entity_id is not None:
        entity = f"{related_entity_type or ''}:{related_entity_id}"
        scope = period
    elif ctx.get("vendor"):
        entity = str(ctx["vendor"])
        scope = period
    else:
        entity = ""
        scope = period
    return compute_fingerprint("watchdog", company_id, alert_type, scope, entity)


# ─────────────────────────────────────────────────────────────────────────────
# Sticky-dismissal checks
# ─────────────────────────────────────────────────────────────────────────────

def is_materially_worse(*, old_severity: Optional[str], new_severity: Optional[str],
                        old_magnitude: Optional[float], new_magnitude: Optional[float]) -> bool:
    """True if the condition deteriorated enough to justify re-alerting a
    dismissed condition: severity escalated, or |magnitude| grew >= 20%
    (MATERIAL_WORSENING_RATIO) vs the dismissed alert's recorded value."""
    old_rank = _SEVERITY_RANK.get((old_severity or "").lower(), 0)
    new_rank = _SEVERITY_RANK.get((new_severity or "").lower(), 0)
    if new_rank > old_rank:
        return True
    if old_magnitude is None or new_magnitude is None:
        return False
    return abs(new_magnitude) >= abs(old_magnitude) * MATERIAL_WORSENING_RATIO


def _sticky_cutoff() -> datetime:
    return datetime.utcnow() - timedelta(days=DISMISSAL_STICKY_DAYS)


def dismissed_anomaly_blocks(db, *, company_id: str, fingerprint: str,
                             new_severity: Optional[str],
                             new_magnitude: Optional[float]) -> bool:
    """True if a recently dismissed InsightAnomaly with the same fingerprint
    should suppress re-creation (i.e. the condition has not materially worsened)."""
    from ..models import InsightAnomaly

    rows = (
        db.query(InsightAnomaly)
        .filter(
            InsightAnomaly.company_id == company_id,
            InsightAnomaly.fingerprint == fingerprint,
            InsightAnomaly.dismissed == True,  # noqa: E712
            InsightAnomaly.dismissed_at >= _sticky_cutoff(),
        )
        .all()
    )
    for row in rows:
        if not is_materially_worse(
            old_severity=row.severity,
            new_severity=new_severity,
            old_magnitude=anomaly_magnitude(row.anomaly_type, row.data_ref),
            new_magnitude=new_magnitude,
        ):
            return True
    return False


def acknowledged_watchdog_blocks(db, *, company_id: str, fingerprint: str,
                                 new_severity: Optional[str],
                                 new_metric_value: Optional[float]) -> bool:
    """True if a recently acknowledged WatchdogAlert with the same fingerprint
    should suppress re-creation (condition has not materially worsened)."""
    from ..models import WatchdogAlert

    rows = (
        db.query(WatchdogAlert)
        .filter(
            WatchdogAlert.company_id == company_id,
            WatchdogAlert.fingerprint == fingerprint,
            WatchdogAlert.acknowledged == True,  # noqa: E712
            WatchdogAlert.acknowledged_at >= _sticky_cutoff(),
        )
        .all()
    )
    for row in rows:
        old_metric = float(row.metric_value) if row.metric_value is not None else None
        if not is_materially_worse(
            old_severity=row.severity,
            new_severity=new_severity,
            old_magnitude=old_metric,
            new_magnitude=new_metric_value,
        ):
            return True
    return False
